            local uid = { id = id, x = x, y = y, options = options }; created[#created + 1] = uid; return uid
        end,
        RemoveWaypoint = function(_, uid) removed[#removed + 1] = uid end,
        SetCrazyArrow = function(_, uid) arrow = uid end,
